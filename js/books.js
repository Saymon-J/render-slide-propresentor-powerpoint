// Дореволюционная орфография → современная (плюс ё→е делается на уровне lower)
const OLD_TO_NEW = { ѣ: "е", Ѣ: "е", ѳ: "ф", Ѳ: "ф", і: "и", І: "и", ѵ: "и", Ѵ: "и", ъ: "", Ъ: "" };
const STRIP = new Set([".", " ", ",", "-", "–", "—", ":", ";", "_", "'"]);

export function normalize(s) {
  let out = "";
  for (const ch of s) out += OLD_TO_NEW[ch] ?? ch;
  out = out.toLowerCase().replaceAll("ё", "е");
  out = [...out].filter((ch) => !STRIP.has(ch)).join("");
  return out;
}

